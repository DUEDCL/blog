/** 会话 id 的形状（前端生成的 uuid）。它要当 DO 的名字用，所以字符集必须收紧 */
const SESSION_RE = /^[0-9a-f-]{8,64}$/i;

/** 知识库在 isolate 里缓存 5 分钟，省掉每次对话都读一遍 `/kb.json` 的 subrequest */
const KB_TTL_MS = 5 * 60 * 1000;
let kbCache: { at: number; items: KbItem[] } | null = null;

/**
 * 读知识库。走 `env.ASSETS.fetch('/kb.json')` —— 那是构建产物里的静态文件，
 * 由 `src/pages/kb.json.ts` 从 `src/content/kb/` 生成。
 * 这么绕是因为 `astro:content` 只存在于 Astro 构建期，这个文件 import 不到它。
 */
async function loadKb(env: Env, base: string): Promise<KbItem[]> {
  if (kbCache && Date.now() - kbCache.at < KB_TTL_MS) return kbCache.items;

  const res = await env.ASSETS.fetch(new Request(new URL('/kb.json', base)));
  if (!res.ok) throw new Error('知识库读不出来');

  const data = (await res.json()) as { items?: KbItem[] };
  const items = Array.isArray(data.items) ? data.items : [];
  // 空知识库比答错更糟：那会让模型完全靠自己编，而 R32 允许它编的前提是「有底座」
  if (!items.length) throw new Error('知识库是空的');

  kbCache = { at: Date.now(), items };
  return items;
}

